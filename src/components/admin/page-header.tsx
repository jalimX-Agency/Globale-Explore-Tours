import type { ReactNode } from "react";

// One consistent title row for every top-level admin page (dashboard, list pages) —
// keeps heading size, description color, and action-button placement from drifting
// page to page as the console grows past Batch 1.
export function PageHeader({
  title,
  description,
  action,
}: {
  title: string;
  description?: string;
  action?: ReactNode;
}) {
  return (
    <div className="flex flex-wrap items-end justify-between gap-4">
      <div className="space-y-1">
        <h1 className="text-2xl font-semibold tracking-tight text-foreground">{title}</h1>
        {description && <p className="text-sm text-muted-foreground">{description}</p>}
      </div>
      {action}
    </div>
  );
}
